import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const credentials=JSON.parse(readFileSync('../../../sites/grc.local/private/grc-local-credentials.json','utf8'));
test('customer login, assessment autosave, Arabic, mobile and ERP denial',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/login');
 await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible();
 await page.screenshot({path:'test-results/login-desktop.png',fullPage:true});
 await page.getByLabel('Email or username').fill('customer@alpha.example.test');
 await page.getByLabel('Password',{exact:true}).fill(credentials['customer@alpha.example.test']);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page).toHaveURL(/\/grc\/customer$/);
 await expect(page.getByRole('heading',{name:'Your assessments'})).toBeVisible();
 await expect(page.getByText('Safa Financial Services')).toHaveCount(0);
 await page.screenshot({path:'test-results/customer-dashboard.png',fullPage:true});
 await page.getByRole('link',{name:'Continue assessment'}).click();
 await expect(page.getByRole('heading',{name:'Al Noor Industries'})).toBeVisible();
 await expect(page.locator('.question-card')).toHaveCount(3);
 const comment=page.locator('.question-card textarea').first();
 await comment.fill('Evidence reviewed during browser acceptance testing.');
 await expect(page.locator('.save-state')).toHaveText(/Saved/);
 await page.reload();
 await expect(page.locator('.question-card textarea').first()).toHaveValue('Evidence reviewed during browser acceptance testing.');
 // Navigation immediately after editing must flush the pending autosave.
 await page.locator('.question-card textarea').first().fill('Saved before navigating away.');
 await page.getByRole('link',{name:'Overview',exact:true}).click();
 await expect(page).toHaveURL(/\/grc\/customer$/);
 await page.getByRole('link',{name:'Continue assessment'}).click();
 await expect(page.locator('.question-card textarea').first()).toHaveValue('Saved before navigating away.');
 await page.screenshot({path:'test-results/assessment-editor.png',fullPage:true});
 await page.getByRole('button',{name:'العربية',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 await page.screenshot({path:'test-results/assessment-arabic.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.reload();
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 const width=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
 expect(width.document).toBeLessThanOrEqual(width.viewport);
 await page.screenshot({path:'test-results/assessment-mobile-arabic.png',fullPage:true});
 const denied=await page.request.get('/api/resource/Customer');expect(denied.status()).toBe(403);
 expect(errors).toEqual([]);
});
test('public pages and deep links render without ERP navigation',async({page})=>{
 await page.goto('/grc-site');
 await expect(page.getByRole('heading',{name:/Stronger governance/})).toBeVisible();
 await page.screenshot({path:'test-results/public-home.png',fullPage:true});
 await page.getByRole('link',{name:'FAQs',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Frequently asked questions'})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:'Frequently asked questions'})).toBeVisible();
 await page.goto('/grc/auditor/admin/settings');
 await expect(page).toHaveURL(/\/login$/);
});
test('auditor login requires MFA before entering the workspace',async({page})=>{
 await page.goto('/login');
 await page.getByLabel('Email or username').fill('auditor@grc.example.test');
 await page.getByLabel('Password',{exact:true}).fill(credentials['auditor@grc.example.test']);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Two-factor authentication'})).toBeVisible();
 await expect(page.getByLabel('Authenticator code')).toBeVisible();
 await expect(page).toHaveURL(/\/login$/);
 await page.screenshot({path:'test-results/mfa.png',fullPage:true});
});
