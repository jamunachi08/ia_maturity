type Language = "en" | "ar";
const Context = createContext<{
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
}>({ lang: "en", setLang: () => {}, t: (key) => key });
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Language>(
    (localStorage.getItem("grc-language") as Language) === "ar" ? "ar" : "en",
  );
  useLayoutEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  useEffect(() => {
    localStorage.setItem("grc-language", lang);
    document.cookie = "preferred_language=" + lang + "; Path=/; SameSite=Lax";
  }, [lang]);
  return (
    <Context.Provider value={{ lang, setLang, t: (key) => (lang === "ar" ? ar[key] || key : key) }}>
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
